"""Generation of the tracked artifacts under ``assets/``.

Everything written here is a *fact about* the cartridge or a *transformation* of
it -- never a copy of any part of the image.  That is the line this repository
draws (see ``docs/CONTRIBUTING.md``), and it is what makes these files safe to
commit while ``data/`` and ``fsdump/`` are not.

Three groups:

``assets/symbols/<component>.txt``
    Address to name, lifted from the disassembly sidecars.  Every name is
    provisional: a retail cartridge has no symbol table, so the disassembler
    emits ``func_<address>`` and a human renames it once the reconstruction
    identifies what it is.
``assets/filesystem.txt``
    The NitroFS listing -- path, file id, size, ROM offset.  A directory tree
    and its file sizes describe how the cartridge is organised; they are not
    expression contained in it.  File *contents* are never included.
``assets/layout.md``
    Header fields, overlay tables, component extents and the digest of the image
    they came from -- the last in the role ``zeldaret/ph`` gives ``ph_usa.sha1``:
    enough for a contributor to confirm they hold the right dump, and no part of
    one.

:func:`find_verbatim_run` makes the rule checkable rather than aspirational, and
:func:`publish` refuses to write an artifact that fails it.
"""

from __future__ import annotations

import json
import os
import re
from typing import Optional

from .rom import NDSRom
from .util import ensure_dir, hexdigest, write_file

__all__ = [
    "ASSETS_DIR",
    "find_verbatim_run",
    "symbol_map",
    "filesystem_listing",
    "layout_document",
    "publish",
]

ASSETS_DIR = "assets"

#: How many contiguous bytes an artifact may share with the image before it is
#: treated as a copy of it rather than a description of it.  Sixteen is far past
#: anything a table of addresses or sizes produces by accident -- offsets are
#: broken up by ``0x`` prefixes and column separators -- while a hexdump of even
#: one line trips it immediately.
VERBATIM_RUN = 16

_HEX_RUN = re.compile(r"(?:[0-9a-fA-F]{2}[\s,]*){%d,}" % VERBATIM_RUN)


def find_verbatim_run(text: str, image: bytes, *, run: int = VERBATIM_RUN) -> Optional[str]:
    """Return an offending hex run if *text* embeds *run* verbatim bytes of *image*.

    The realistic way cartridge data reaches a committed file is a pasted
    hexdump, so this looks for runs of hex byte pairs rather than for raw bytes:
    an artifact is text, and most cartridge bytes are not printable.  ``0x``
    prefixes and column separators break candidate runs, which is what keeps
    address tables from tripping the check.
    """
    for match in _HEX_RUN.finditer(text):
        digits = re.sub(r"[^0-9a-fA-F]", "", match.group(0))
        if len(digits) % 2:
            digits = digits[:-1]
        candidate = bytes.fromhex(digits)
        for offset in range(0, max(1, len(candidate) - run + 1)):
            window = candidate[offset : offset + run]
            if len(window) == run and window in image:
                return window.hex()
    return None


def symbol_map(sidecar: dict) -> str:
    """Render one disassembly sidecar as an address-to-name table."""
    name = sidecar.get("name", "?")
    base = int(sidecar.get("base_address", 0))
    stats = sidecar.get("stats", {})
    functions = {int(f["start"]): int(f["end"]) for f in sidecar.get("functions", [])}

    lines = [
        f"# {name} -- symbol map",
        f"# base 0x{base:08x}    {stats.get('functions', 0)} functions    "
        f"{stats.get('image_bytes', 0)} image bytes "
        f"({stats.get('code_bytes', 0)} code, {stats.get('data_bytes', 0)} data)",
        "#",
        "# Generated by `sr assets` from the disassembly sidecar.  Every name here",
        "# is provisional: a retail cartridge carries no symbol table, so the",
        "# disassembler emits func_<address> and loc_<address>, and a human",
        "# renames them as the reconstruction works out what they are.  Edit this",
        "# file -- it is tracked, and renaming a symbol is the work.",
        "#",
        "#  address       size  mode   kind         name",
    ]
    for label in sorted(sidecar.get("labels", []), key=lambda l: int(l["address"])):
        address = int(label["address"])
        end = functions.get(address)
        size = f"0x{end - address:x}" if end else "-"
        lines.append(
            f"0x{address:08x}  {size:>7}  {label.get('mode', '?'):<5} "
            f"{label.get('kind', '?'):<12} {label.get('name', '?')}"
        )
    return "\n".join(lines) + "\n"


def filesystem_listing(fs) -> str:
    """The NitroFS as a listing of paths, ids and sizes -- no file contents."""
    lines = [
        "# NitroFS listing",
        "#",
        "# Generated by `sr assets`.  Paths, file ids and sizes describe how the",
        "# cartridge organises its data.  File contents are deliberately absent:",
        "# they are verbatim cartridge bytes and belong in fsdump/, which is",
        "# gitignored.",
        "#",
        f"# {len(fs)} files, {len(fs.directories)} directories, "
        f"{len(fs.fat)} FAT entries",
        "#",
        "#      id      size  rom offset  path",
    ]
    total = 0
    for entry in sorted(fs, key=lambda e: (e.file_id, e.path)):
        if not 0 <= entry.file_id < len(fs.fat):
            lines.append(f"{entry.file_id:>7}  {'-':>9}  {'-':>10}  {entry.path}  (no FAT slot)")
            continue
        slot = fs.fat[entry.file_id]
        total += slot.size
        lines.append(
            f"{entry.file_id:>7}  0x{slot.size:07x}  0x{slot.start:08x}  {entry.path}"
        )

    lines += ["", f"total file bytes: 0x{total:x} ({total / 1048576:.2f} MiB)"]

    histogram = fs.extension_histogram()
    if histogram:
        lines += ["", "by extension:"]
        for ext, (count, size) in histogram.items():
            lines.append(f"  {ext:<10} {count:>5} files  {size / 1024:>10.1f} KiB")

    for warning in fs.warnings:
        lines.append(f"warning: {warning}")
    return "\n".join(lines) + "\n"


def _overlay_section(title: str, table) -> list[str]:
    if table is None or not len(table):
        return [f"### {title}", "", "_none_", ""]
    lines = [
        f"### {title}",
        "",
        "| overlay id | RAM address | RAM size | BSS size | static init | file id | compressed |",
        "|---:|---|---:|---:|---|---:|---|",
    ]
    for overlay in table:
        static_init = (
            f"`0x{overlay.static_init_start:08x}`..`0x{overlay.static_init_end:08x}`"
            if overlay.static_init_end > overlay.static_init_start
            else "-"
        )
        lines.append(
            f"| {overlay.overlay_id} | `0x{overlay.ram_address:08x}` | "
            f"0x{overlay.ram_size:x} | 0x{overlay.bss_size:x} | {static_init} | "
            f"{overlay.file_id} | "
            f"{overlay.compressed_flag_source or 'no'} |"
        )
    lines.append("")
    return lines


def layout_document(rom: NDSRom, sidecars: Optional[list[dict]] = None) -> str:
    """The structural facts about an image, as Markdown.

    Includes the image digest in the role ``zeldaret/ph`` gives its committed
    ``ph_usa.sha1``: a contributor can confirm they hold the same dump without
    anyone distributing it.
    """
    header = rom.header
    lines = [
        "# Cartridge layout",
        "",
        "Generated by `sr assets`. Every value here is a header field, a table",
        "entry, or a measurement -- facts about how the cartridge is built. No",
        "part of the image is reproduced.",
        "",
        "## Identity",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Title | `{header.game_title}` |",
        f"| Game code | `{header.game_code}` |",
        f"| Maker code | `{header.maker_code}` |",
        f"| Unit code | {header.unit_code} |",
        f"| Region | {header.region} |",
        f"| ROM version | {header.rom_version} |",
        f"| Device capacity | {header.device_capacity} "
        f"(0x{header.rom_capacity:x} = {header.rom_capacity // 1048576} MiB) |",
        "",
        "## The image this was generated from",
        "",
        "Publish the digest, never the image. A contributor compares these against",
        "their own dump to confirm the revision matches.",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Size | 0x{len(rom.data):x} ({len(rom.data):,} bytes) |",
        f"| SHA-256 | `{rom.digest()}` |",
        f"| MD5 | `{hexdigest(rom.data, 'md5')}` |",
        "",
        "```",
        *rom.size_report(),
        "```",
        "",
        "## Header extents",
        "",
        "| Region | ROM offset | Size |",
        "|---|---|---:|",
        f"| ARM9 | `0x{header.arm9_rom_offset:08x}` | 0x{header.arm9_size:x} |",
        f"| ARM7 | `0x{header.arm7_rom_offset:08x}` | 0x{header.arm7_size:x} |",
        f"| FNT | `0x{header.fnt_offset:08x}` | 0x{header.fnt_size:x} |",
        f"| FAT | `0x{header.fat_offset:08x}` | 0x{header.fat_size:x} "
        f"({header.fat_size // 8} entries) |",
        f"| Y9 overlays | `0x{header.arm9_overlay_offset:08x}` | "
        f"0x{header.arm9_overlay_size:x} ({header.arm9_overlay_size // 32}) |",
        f"| Y7 overlays | `0x{header.arm7_overlay_offset:08x}` | "
        f"0x{header.arm7_overlay_size:x} ({header.arm7_overlay_size // 32}) |",
        f"| Banner | `0x{header.banner_offset:08x}` | 0x{header.banner_size:x} |",
        "",
        "## Components",
        "",
        "Compression is taken from an authoritative source only -- the ARM9 footer",
        "or an overlay table flag -- never guessed at from a leading byte. `source`",
        "records which decided it.",
        "",
        "| Component | ROM offset | On media | Payload | Entry | RAM | Compressed | source |",
        "|---|---|---:|---:|---|---|---|---|",
    ]

    for image in (rom.arm9, rom.arm7):
        lines.append(
            f"| `{image.name}` | `0x{image.rom_offset:08x}` | "
            f"0x{image.size_on_media:x} | 0x{image.payload_size:x} | "
            f"`0x{image.entry_address:08x}` | `0x{image.ram_address:08x}` | "
            f"{'yes' if image.compressed else 'no'} | {image.compression_source} |"
        )

    lines += ["", *_overlay_section("ARM9 overlays", rom.arm9_overlays)]
    lines += [*_overlay_section("ARM7 overlays", rom.arm7_overlays)]

    if sidecars:
        lines += [
            "## Disassembly",
            "",
            "| Component | Functions | Instructions | Code bytes | Data bytes | Unresolved tails |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for sidecar in sidecars:
            stats = sidecar.get("stats", {})
            lines.append(
                f"| `{sidecar.get('name', '?')}` | {stats.get('functions', 0)} | "
                f"{stats.get('instructions', 0)} | {stats.get('code_bytes', 0)} | "
                f"{stats.get('data_bytes', 0)} | {stats.get('unresolved_tails', 0)} |"
            )
        lines.append("")

    return "\n".join(lines) + "\n"


def publish(
    rom: NDSRom, *, asm_dir: str = "asm", out_dir: str = ASSETS_DIR
) -> list[str]:
    """Write every tracked artifact for *rom*; return the paths written.

    Raises ``ValueError`` if any generated text shares a verbatim run with the
    image.  Refusing to write is the point: the check is worthless if it reports
    a leak into a file that has already been committed.
    """
    ensure_dir(out_dir)
    symbols_dir = os.path.join(out_dir, "symbols")
    ensure_dir(symbols_dir)

    sidecars: list[dict] = []
    if os.path.isdir(asm_dir):
        for filename in sorted(os.listdir(asm_dir)):
            if not filename.endswith(".json"):
                continue
            with open(os.path.join(asm_dir, filename), encoding="utf-8") as handle:
                sidecars.append(json.load(handle))

    planned: list[tuple[str, str]] = [
        (os.path.join(out_dir, "layout.md"), layout_document(rom, sidecars)),
    ]
    try:
        planned.append(
            (os.path.join(out_dir, "filesystem.txt"), filesystem_listing(rom.filesystem))
        )
    except (IndexError, ValueError) as error:
        # An unreadable file system is worth recording, not worth aborting for:
        # the layout document is still useful on its own.
        planned.append(
            (
                os.path.join(out_dir, "filesystem.txt"),
                f"# NitroFS listing unavailable: {error}\n",
            )
        )

    for sidecar in sidecars:
        name = sidecar.get("name", "component")
        planned.append(
            (os.path.join(symbols_dir, f"{name}.txt"), symbol_map(sidecar))
        )

    written: list[str] = []
    for path, text in planned:
        leak = find_verbatim_run(text, rom.data)
        if leak is not None:
            raise ValueError(
                f"{path} would embed {VERBATIM_RUN} verbatim bytes of the "
                f"cartridge image ({leak}); refusing to write it"
            )
        write_file(path, text.encode("utf-8"))
        written.append(path)
    return written
